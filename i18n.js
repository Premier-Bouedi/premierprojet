const LANG_KEY = "portfolio-lang";
let currentLang = localStorage.getItem(LANG_KEY) || "en";

function t(key) {
  return translations[currentLang]?.[key] ?? translations.en[key] ?? key;
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem(LANG_KEY, lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = t(key);
    if (el.hasAttribute("data-i18n-html")) {
      el.innerHTML = value;
    } else {
      el.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });

  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const isActive = btn.dataset.lang === lang;
    btn.classList.toggle("lang-btn-active", isActive);
    btn.setAttribute("aria-pressed", String(isActive));
  });

  // Refresh CV toggle label if modal state is known
  const cvModal = document.getElementById("cv-modal");
  const cvToggleBtn = document.getElementById("cv-toggle-btn");
  if (cvToggleBtn && cvModal) {
    const isOpen = !cvModal.classList.contains("hidden");
    cvToggleBtn.innerHTML = isOpen
      ? `<i class="fa-solid fa-eye-slash mr-1"></i> ${t("about.cv.hide")}`
      : `<i class="fa-solid fa-eye mr-1"></i> ${t("about.cv.view")}`;
  }

  document.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
  });
  setLanguage(currentLang);
});
